def status_cell(kind: str):
    if kind == "ok":
        return P("РАБОТАЕТ", "StatusOk")
    if kind == "part":
        return P("ЧАСТИЧНО", "StatusWarn")
    return P("НЕТ", "StatusNo")


def table(headers, rows, col_widths, status_col=None):
    head = [P(h, "Th") for h in headers]
    data = [head]
    for r in rows:
        line = []
        for i, cell in enumerate(r):
            if status_col is not None and i == status_col:
                line.append(status_cell(cell) if cell in ("ok", "part", "no") else P(str(cell), "Cell"))
            else:
                line.append(P(str(cell), "CellB" if i == 0 else "Cell"))
        data.append(line)
    t = Table(data, colWidths=col_widths, repeatRows=1)
    cmd = [
        ("BACKGROUND", (0, 0), (-1, 0), FOREST),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), "Sans-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("GRID", (0, 0), (-1, -1), 0.3, LINE),
        ("BACKGROUND", (0, 1), (-1, -1), SURFACE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [SURFACE, PAPER]),
    ]
    if status_col is not None:
        for i, r in enumerate(rows, start=1):
            st = r[status_col]
            bg = OK_BG if st == "ok" else WARN_BG if st == "part" else NO_BG
            cmd.append(("BACKGROUND", (status_col, i), (status_col, i), bg))
    t.setStyle(TableStyle(cmd))
    return t


